function handleBottomNavigation(
    screenId
) {

    const nav =
        document.getElementById(
            "bottomNav"
        );


    const patientScreens = [
        "homeScreen",
        "nearbyScreen",
        "appointmentsScreen",
        "healthScreen",
        "profileScreen",
        "facilityDetailsScreen",
        "notificationsScreen",
        "emergencyScreen"
    ];


    nav.style.display =
        patientScreens.includes(
            screenId
        )
        ? "grid"
        : "none";


    document
        .querySelectorAll(
            ".nav-item"
        )
        .forEach(item => {

            item.classList.toggle(
                "active",
                item.dataset.screen ===
                    screenId
            );

        });

}


