function getSaved(key) {

    try {

        const data =
            localStorage.getItem(
                key
            );


        return data
            ? JSON.parse(data)
            : null;

    }

    catch (error) {

        console.error(
            error
        );

        return null;

    }

}


function showToast(message) {

    const toast =
        document.getElementById(
            "toast"
        );


    toast.textContent =
        message;


    toast.classList.add(
        "show"
    );


    clearTimeout(
        toastTimer
    );


    toastTimer =
        setTimeout(
            function () {

                toast.classList.remove(
                    "show"
                );

            },
            2800
        );

}